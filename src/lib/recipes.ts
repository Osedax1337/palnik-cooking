export function searchRecipe(recipe: Recipe, query: string) {
  const normalizedQuery = query.trim().toLowerCase()
  if (!normalizedQuery) return true

  return [
    recipe.title,
    recipe.intro,
    recipe.cuisine,
    recipe.tag,
    recipe.ingredients.map((i) => `${i.name} ${i.note ?? ''} ${i.key}`).join(' '),
    recipe.steps.join(' '),
    recipe.dietTags.join(' '),
  ]
    .join(' ')
    .toLowerCase()
    .includes(normalizedQuery)
}

function formatAmount(value: number): string {
  if (value <= 0) return '0'
  if (Math.abs(value - 0.25) < 0.01) return '¼'
  if (Math.abs(value - 0.5) < 0.01) return '½'
  if (Math.abs(value - 0.75) < 0.01) return '¾'
  if (Math.abs(value - 1.5) < 0.01) return '1½'
  if (Math.abs(value - 2.5) < 0.01) return '2½'
  if (Number.isInteger(value)) return String(value)
  const rounded = Math.round(value * 4) / 4
  if (Number.isInteger(rounded)) return String(rounded)
  return rounded.toFixed(2).replace('.', ',').replace(/,?0+$/, '')
}

export function renderIngredient(ingredient: Ingredient, ratio = 1): string {
  if (ingredient.scalable && ingredient.amount != null) {
    const scaled = ingredient.amount * ratio
    const amountStr = formatAmount(scaled)
    const parts = [amountStr, ingredient.unit, ingredient.name].filter(Boolean) as string[]
    return ingredient.note ? `${parts.join(' ')} ${ingredient.note}` : parts.join(' ')
  }
  const parts = [ingredient.unit, ingredient.name].filter(Boolean) as string[]
  return ingredient.note ? `${parts.join(' ')} ${ingredient.note}` : parts.join(' ')
}

// Aggregate of all non-pantry ingredient keys, with display label & how many recipes use them.
export function buildFridgePalette() {
  const counts = new Map<string, number>()
  for (const recipe of recipes) {
    for (const ing of recipe.ingredients) {
      if (ing.pantry) continue
      counts.set(ing.key, (counts.get(ing.key) ?? 0) + 1)
    }
  }
  return Array.from(counts.entries())
    .map(([key, count]) => ({ key, count }))
    .sort((a, b) => b.count - a.count || a.key.localeCompare(b.key))
}

export function fridgeMatch(recipe: Recipe, selected: Set<string>) {
  const required = recipe.ingredients.filter((ing) => !ing.pantry)
  if (required.length === 0) return { score: 1, matched: 0, total: 0, missing: [] as Ingredient[] }
  const matched = required.filter((ing) => selected.has(ing.key))
  const missing = required.filter((ing) => !selected.has(ing.key))
  return {
    score: matched.length / required.length,
    matched: matched.length,
    total: required.length,
    missing,
  }
}
