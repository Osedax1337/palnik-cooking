const PANTRY: Record<string, true> = { sól: true, pieprz: true, oliwa: true, olej: true }

function ing(input: Omit<Ingredient, 'pantry'> & { pantry?: boolean }): Ingredient {
  return { ...input, pantry: input.pantry ?? PANTRY[input.key] === true }
}

